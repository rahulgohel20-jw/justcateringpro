import { Tooltip, Switch } from "antd";
import { FormattedMessage } from "react-intl";

export const columns = (onDelete, onEdit, intl, onStatus) => [
  {
    accessorKey: "sr_no",
    header: <FormattedMessage id="COMMON.SR_NO" defaultMessage="Sr No" />,
    meta: {
      headerClassName: "w-[4%]",
      cellClassName: "w-[4%]",
    },
  },
  {
    accessorKey: "name",
    header: (
      <FormattedMessage id="USER_TERMS.NAME" defaultMessage="Name" />
    ),
    meta: {
      headerClassName: "w-[15%]",
      cellClassName: "w-[15%]",
    },
    cell: ({ row }) => {
      const data = row.original;
      const locale = intl.locale;
      let displayName = data.nameEnglish;
      if (locale === "gu" && data.nameGujarati) displayName = data.nameGujarati;
      else if (locale === "hi" && data.nameHindi) displayName = data.nameHindi;

      return (
        <div>
          <span className="font-semibold text-gray-800 text-sm">{displayName || data.name}</span>
          {displayName !== data.nameEnglish && data.nameEnglish && (
            <div className="text-xs text-gray-400 mt-0.5">{data.nameEnglish}</div>
          )}
        </div>
      );
    },
  },
  {
    accessorKey: "description",
    header: (
      <FormattedMessage
        id="USER_TERMS.DESCRIPTION"
        defaultMessage="Description"
      />
    ),
    cell: ({ row }) => {
      const desc = row.original.description;
      const list = Array.isArray(desc) ? desc : [];
      const locale = intl.locale;

      const getItemText = (item) => {
        if (!item) return "";
        if (typeof item === "string") return item;
        if (locale === "gu" && item.descriptionGujarati) return item.descriptionGujarati;
        if (locale === "hi" && item.descriptionHindi) return item.descriptionHindi;
        return (
          item.descriptionEnglish ||
          item.description ||
          item.descriptionGujarati ||
          item.descriptionHindi ||
          ""
        );
      };

      return (
        <ul className="list-disc pl-4 space-y-1.5">
          {list.map((d, i) => {
            const htmlText = getItemText(d);
            return (
              <li
                key={i}
                className="text-sm text-gray-700 leading-relaxed"
                dangerouslySetInnerHTML={{ __html: htmlText }}
              />
            );
          })}
        </ul>
      );
    },
    meta: {
      headerClassName: "w-[55%]",
      cellClassName: "w-[55%]",
    },
  },
  {
    accessorKey: "isActive",
    header: (
      <FormattedMessage id="COMMON.STATUS" defaultMessage="Status" />
    ),
    cell: ({ row }) => {
      const active = row.original.isActive ?? true;
      return (
        <div className="flex items-center gap-2">
          <Switch
            checked={active}
            onChange={(checked) =>
              onStatus &&
              onStatus(row.original.id, checked, row.original)
            }
          />
          <span
            className={`text-xs font-semibold ${
              active ? "text-green-600" : "text-gray-400"
            }`}
          >
            {active ? (
              <FormattedMessage id="COMMON.ACTIVE" defaultMessage="Active" />
            ) : (
              <FormattedMessage id="COMMON.INACTIVE" defaultMessage="Inactive" />
            )}
          </span>
        </div>
      );
    },
    meta: {
      headerClassName: "w-[12%]",
      cellClassName: "w-[12%]",
    },
  },
  {
    accessorKey: "action",
    header: <FormattedMessage id="COMMON.ACTIONS" defaultMessage="Action" />,
    cell: ({ row }) => {
      const rowData = row.original;
      return (
        <div className="flex items-center gap-1">
          <Tooltip title={intl.formatMessage({ id: "USER_TERMS.EDIT_EVENT", defaultMessage: "Edit Event" })}>
            <button
              className="btn btn-sm btn-icon btn-clear"
              onClick={() => onEdit(rowData)}
            >
              <i className="ki-filled ki-notepad-edit text-primary"></i>
            </button>
          </Tooltip>

          <Tooltip title={intl.formatMessage({ id: "COMMON.DELETE", defaultMessage: "Delete" })}>
            <button
              className="btn btn-sm btn-icon btn-clear"
              onClick={() => onDelete(rowData.id, rowData)}
            >
              <i className="ki-filled ki-trash text-danger"></i>
            </button>
          </Tooltip>
        </div>
      );
    },
    meta: {
      headerClassName: "w-[8%]",
      cellClassName: "w-[8%]",
    },
  },
];
